// Embed the Effect TypeScript conformance programs so `forma mcp`'s REPL can show
// them from an installed package. Run after adding or editing a case.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import assert from "node:assert/strict";
import { join, resolve } from "node:path";

const casesDir = resolve(import.meta.dirname, "../../../conformance/effect-typescript/cases");
export const examplesOutput = resolve(import.meta.dirname, "../src/cli/examples.generated.ts");

/** Cases that a single-source Effect program checks; marker files select other linkers (Elm, email, Cluster, HTTP API). */
export function renderExamples() {
  const examples = readdirSync(casesDir).sort().flatMap(name => {
    const dir = join(casesDir, name);
    if (readdirSync(dir).some(file => file.endsWith(".json") && file !== "expected-diagnostics.json")) return [];
    const program = readFileSync(join(dir, "program.lisp"), "utf8");
    const summary = program.split("\n").filter((line, index, lines) => lines.slice(0, index + 1).every(l => l.startsWith(";")))
      .map(line => line.replace(/^;+\s?/u, "")).join(" ").trim();
    const expected = join(dir, "expected-diagnostics.json");
    const diagnostics = existsSync(expected)
      ? JSON.parse(readFileSync(expected, "utf8")).diagnostics.map(({ code, message, line, column }) => ({ code, message, line, column }))
      : undefined;
    return [{ name, summary, outcome: diagnostics ? "rejected" : "runs", program, ...(diagnostics ? { diagnostics } : {}) }];
  });
  return [
    "// Generated by scripts/generate-examples.mjs from conformance/effect-typescript/cases. Do not edit.",
    "",
    `export const effectExamples = ${JSON.stringify(examples, null, 2)} as const;`,
    "",
  ].join("\n");
}

if (process.argv[1] === import.meta.filename) {
  if (process.argv.includes("--check")) assert.equal(readFileSync(examplesOutput, "utf8"), renderExamples(), "run pnpm --filter @formalang/host examples:generate");
  else writeFileSync(examplesOutput, renderExamples());
}
