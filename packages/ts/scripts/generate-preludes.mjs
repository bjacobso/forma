// Embed the repository preludes as strings so `@formalang/ts/preludes` works in
// any runtime without file-system access. Run after editing `preludes/*.lisp`.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const preludesDir = resolve(import.meta.dirname, "../../../preludes");
const output = resolve(import.meta.dirname, "../src/preludes/sources.generated.ts");

export const renderPreludeSources = () => {
  const names = readdirSync(preludesDir).filter((name) => name.endsWith(".lisp")).sort();
  const entries = names.map(
    (name) => `  ${JSON.stringify(name)}: ${JSON.stringify(readFileSync(resolve(preludesDir, name), "utf8"))},`,
  );
  return [
    "// Generated by scripts/generate-preludes.mjs from preludes/*.lisp. Do not edit.",
    "",
    "export const preludeSources = {",
    ...entries,
    "} as const;",
    "",
  ].join("\n");
};

if (process.argv[1] === import.meta.filename) {
  writeFileSync(output, renderPreludeSources());
  console.log(`Wrote ${output}`);
}
