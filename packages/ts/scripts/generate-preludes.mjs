// Embed the repository preludes as strings so `@formalang/ts/preludes` works in
// any runtime without file-system access. Run after editing preludes, including modules/.
import "./derive-domain-protocol.mjs";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import assert from "node:assert/strict";
import { resolve } from "node:path";

const preludesDir = resolve(import.meta.dirname, "../../../preludes");
const output = resolve(import.meta.dirname, "../src/preludes/sources.generated.ts");

export const renderPreludeSources = () => {
  // Legacy shared-scope preludes and isolated file-module libraries stay separate.
  const names = readdirSync(preludesDir).filter((name) => name.endsWith(".lisp")).sort();
  const entries = names.map(
    (name) => `  ${JSON.stringify(name)}: ${JSON.stringify(readFileSync(resolve(preludesDir, name), "utf8"))},`,
  );
  return [
    "// Generated by scripts/generate-preludes.mjs from preludes/*.lisp. Do not edit.",
    "",
    "export const preludeSources = {",
    ...entries,
    "} as const;",
    "",
  ].join("\n");
};

const moduleOutput = resolve(import.meta.dirname, "../src/modules/sources.generated.ts");
const renderModuleSources = () => [
  "// Generated by scripts/generate-preludes.mjs from preludes/modules/*.lisp. Do not edit.",
  "",
  "export const bundledModuleSources = {",
  ...readdirSync(resolve(preludesDir, "modules")).filter(name => name.endsWith(".lisp")).sort().map(name =>
    `  ${JSON.stringify(name.slice(0, -5))}: ${JSON.stringify(readFileSync(resolve(preludesDir, "modules", name), "utf8"))},`),
  "} as const;",
  "",
].join("\n");

if (process.argv[1] === import.meta.filename) {
  const kernel = readFileSync(resolve(preludesDir, "kernel.lisp"), "utf8");
  const moduleKernel =
    "; Generated from kernel.lisp by packages/ts/scripts/generate-preludes.mjs.\n" +
    "(export not when unless cond and or -> ->>)\n\n" + kernel;
  const kernelOutput = resolve(preludesDir, "modules/kernel.lisp");
  if (process.argv.includes("--check")) {
    for (const [path, expected] of [[kernelOutput, moduleKernel], [output, renderPreludeSources()], [moduleOutput, renderModuleSources()]])
      assert.equal(readFileSync(path, "utf8"), expected, `${path}: run pnpm --filter @formalang/ts preludes:generate`);
  } else {
    writeFileSync(kernelOutput, moduleKernel);
    writeFileSync(output, renderPreludeSources());
    writeFileSync(moduleOutput, renderModuleSources());
    console.log(`Wrote ${output} and ${moduleOutput}`);
  }
}
